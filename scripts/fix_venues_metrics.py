def main() -> None:
    venues = json.loads(PATH.read_text(encoding="utf-8"))
    fixed_j = fixed_c = 0
    for v in venues:
        abbr = v["abbr"]
        if v["kind"] == "journal":
            if abbr in JOURNAL_IF_2024:
                new_if = JOURNAL_IF_2024[abbr]
                if abs(float(v.get("impactFactor") or 0) - new_if) > 0.05:
                    fixed_j += 1
                v["impactFactor"] = new_if
            v["metricKind"] = "impact-factor"
            v["metricLabel"] = "Journal Impact Factor (approx. JCR 2024)"
            v["metricYear"] = 2024
            v["citationNote"] = (
                "ضریب تأثیر تقریبی بر اساس گزارش‌های عمومی JCR حدود ۲۰۲۴؛ قبل از استناد، JCR/سایت ناشر را چک کنید."
            )
            if v["impactFactor"] <= 0:
                v["citationNote"] = "ژورنال جدید/بدون IF کلاسیک ثبت‌شده؛ به CiteScore یا سیاست ناشر رجوع کنید."
        else:
            h5 = CONF_H5.get(abbr)
            # convert previous fake IF into clearer fields
            if h5 is not None:
                v["h5Index"] = h5
                v["impactFactor"] = float(h5)  # keep numeric sort key = h5
                fixed_c += 1
            else:
                # demote old prestige proxies that looked like IF (10–25) into soft score
                old = float(v.get("impactFactor") or 0)
                v["h5Index"] = int(max(10, min(120, old * 3))) if old else 20
                v["impactFactor"] = float(v["h5Index"])
            v["metricKind"] = "h5-index"
            v["metricLabel"] = "Google Scholar h5-index (approx.)"
            v["metricYear"] = 2024
            v["citationNote"] = (
                "برای کنفرانس‌ها Impact Factor وجود ندارد؛ عدد نمایش‌داده‌شده h5 تقریبی/امتیاز استناد است، نه IF."
            )

        if abbr in RIGOR_FIX:
            v["rigor"] = RIGOR_FIX[abbr]

        # acceptance hint refresh
        if v["kind"] == "journal":
            hints = {1: "~35%+", 2: "~20–35%", 3: "~12–20%", 4: "~6–12%", 5: "<6% / بسیار گزینشی"}
        else:
            hints = {1: "~35%+", 2: "~22–35%", 3: "~15–22%", 4: "~8–15%", 5: "<10% پرچم‌دار"}
        v["acceptanceHint"] = hints.get(int(v["rigor"]), v.get("acceptanceHint", "n/a"))

    PATH.write_text(json.dumps(venues, ensure_ascii=False, indent=2), encoding="utf-8")
    print("journals IF touched", fixed_j, "conferences h5 set", fixed_c, "total", len(venues))


if __name__ == "__main__":
    main()
